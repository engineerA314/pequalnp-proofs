"""Check every exported wire after fixing a small set of ordinary lines.

The calculation propagates constants and variable types. An output labeled
points or lines can depend on arbitrarily many inputs of that type. The
certificate quantifies over every assignment to the unfixed inputs.
"""

from collections import Counter
from enum import Enum
from math import comb

import square_projection_circuit as square


class Kind(Enum):
    ZERO = "zero"
    ONE = "one"
    POINT = "points"
    LINE = "lines"
    MIXED = "mixed"


def gate_kind(op, left, right):
    absorbing, neutral = (Kind.ZERO, Kind.ONE) if op == "and" else (Kind.ONE, Kind.ZERO)
    if left is absorbing or right is absorbing:
        return absorbing
    if left is neutral:
        return right
    if right is neutral or left is right:
        return left
    return Kind.MIXED


def cofactor(circuit, q, anchors):
    n = q*q + q + 1
    assert circuit.inputs == 2*n and all(0 <= w < q*q for w in anchors)
    # We use affine points and ordinary lines only in this subproblem.
    state = [Kind.POINT]* (q*q) + [Kind.ZERO]*(q+1)
    state += [Kind.ONE if w in anchors else Kind.LINE for w in range(q*q)] + [Kind.ZERO]*(q+1)
    for op, a, b in circuit.gates:
        state.append(gate_kind(op, state[a], state[b]))
    return state


def square_anchors(field, t):
    s = field.s
    if t < s:
        # The omitted finite direction t has kernel generated by (-t, 1).
        return {field.pair(field.times[h][field.neg[t]], h) for h in range(s)}
    return {field.pair(h, 0) for h in range(s)} | {field.pair(0, h) for h in range(s)}


def report(name, circuit, q, anchors):
    states = cofactor(circuit, q, anchors)
    counts = Counter(states)
    assert counts[Kind.MIXED] == 0, (name, q, counts)
    assert states[circuit.output] is Kind.POINT
    budget = q-1-len(anchors)
    lower = sum(comb(q*q-len(anchors), j) for j in range(budget+1))
    ands = (lower-1).bit_length() if lower else 0
    print(f"{name} q={q} anchors={len(anchors)} checked wires={len(states)} "
          f"mixed={counts[Kind.MIXED]} separated negative rows={lower} suffix ANDs>={ands}")


def main():
    if not __debug__:
        raise SystemExit("Run Python without -O so replay assertions are active.")
    library = square.circuit_library()
    for k in range(2, 7):
        q = 2**k
        circuit, _ = library.one_line_circuit(k)
        report("one-line", circuit, q, {0, q-1})
    for s in (2, 3, 4, 5):
        field = square.SquareField(s, library)
        for t in range(1, s+1):
            circuit = square.build(field, t, library)
            anchors = square_anchors(field, t)
            assert len(anchors) == (s if t < s else 2*s-1)
            for d in square.selected_directions(s, t):
                assert {field.project(d, b) for b in anchors} == set(range(s))
            report(f"projection-t{t}", circuit, field.q, anchors)


if __name__ == "__main__":
    main()
